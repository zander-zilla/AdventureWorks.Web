"""Render docs/business-processes/* from processes.py + evidence.json. CI checks the output is in sync."""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from processes import PROCESSES, CANDIDATES

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "docs", "business-processes")
ev = json.load(open(os.path.join(OUT, "evidence.json")))["metrics"]
ap = {p["id"]: p for p in json.load(open(os.path.join(ROOT, "docs", "design", "access-patterns.json")))["patterns"]}

def fmt(v):
    return f"{v:,}" if isinstance(v, int) else str(v)

def evidence_rows(p):
    rows = []
    for e in p["evidence"]:
        m = ev.get(e["metric"])
        if m is None:
            raise SystemExit(f"{p['id']}: metric {e['metric']} missing from evidence.json")
        keys = e.get("keys") or list(m)
        missing = [k for k in keys if k not in m]
        if missing:
            raise SystemExit(f"{p['id']}: {e['metric']} has no key(s) {missing}")
        rows.append({"metric": e["metric"], "values": {k: m[k] for k in keys}, "note": e.get("note", "")})
    return rows

def pid(a):
    return a.split(" ")[0]

out_json = {"generated_by": "scripts/business-processes/render.py", "evidence_source": "evidence.json",
            "basis_legend": {"evidenced": "visible in the live AdventureWorks2022 data, FKs, triggers or procs",
                             "inferred": "what the data implies a business would do, not provable from the DB"},
            "processes": [], "chapter2_candidates": CANDIDATES}
for p in PROCESSES:
    for a in p["coverage"]["access_patterns"]:
        if pid(a) not in ap:
            raise SystemExit(f"{p['id']}: unknown access pattern {a}")
    q = dict(p)
    q["file"] = f"{p['id']}.md"
    q["evidence"] = evidence_rows(p)
    q["coverage"] = dict(p["coverage"], access_patterns=[{"id": pid(a), "question": ap[pid(a)]["question"], "scope": ap[pid(a)]["scope"]} for a in p["coverage"]["access_patterns"]])
    q["state_values"] = {str(k): v for k, v in p["state_values"].items()}
    q["counts"] = {"steps": len(p["steps"]), "evidenced_steps": sum(s["basis"] == "evidenced" for s in p["steps"]),
                   "app_pages": len(p["coverage"]["app_pages"]), "gaps": len(p["gaps"])}
    out_json["processes"].append(q)

with open(os.path.join(OUT, "business-processes.json"), "w") as f:
    json.dump(out_json, f, indent=1, ensure_ascii=False); f.write("\n")

TAG = {"evidenced": "**E**", "inferred": "*I*"}
for q in out_json["processes"]:
    L = [f"# {q['name']}", "", f"> Generated by `scripts/business-processes/render.py` from `processes.py` + [`evidence.json`](evidence.json). Do not edit by hand.",
         "", q["summary"], "", f"**Domain:** {q['domain']}  ", f"**Actors:** {', '.join(q['actors'])}  ", f"**Trigger:** {q['trigger']}", "",
         "Basis: **E** = evidenced in the data / schema, *I* = inferred.", "", "## Process flow", "", "```mermaid", q["flowchart"], "```", "",
         "## Steps", "", "| # | Step | Actor | Reads | Writes | Basis | Notes |", "|---|---|---|---|---|---|---|"]
    for i, s in enumerate(q["steps"], 1):
        L.append(f"| {i} | {s['name']} | {s['actor']} | {'<br>'.join(s['reads']) or '–'} | {'<br>'.join(s['writes']) or '–'} | {TAG[s['basis']]} | {s['note']} |")
    L += ["", f"## State machine: `{q['state_entity']}`", "", "| Value | Meaning |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in q["state_values"].items()]
    L += ["", "```mermaid", q["state_diagram"], "```", "", "## Evidence", "", "| Metric | Values | Note |", "|---|---|---|"]
    for e in q["evidence"]:
        vals = "<br>".join(f"{k}: {fmt(v)}" for k, v in e["values"].items())
        L.append(f"| `{e['metric']}` | {vals} | {e['note']} |")
    c = q["coverage"]
    L += ["", "## Coverage in the modernized system", "", "**DynamoDB access patterns (designed, loaded, tested):**", ""]
    L += [f"- `{a['id']}` ({a['scope']}) {a['question']}" for a in c["access_patterns"]]
    L += ["", "**App pages:** " + ("; ".join(c["app_pages"]) or "none"), "", "**Redshift:** " + ("; ".join(c["redshift"]) or "none"), "",
          "## Gaps", ""] + [f"- {g}" for g in q["gaps"]] + [""]
    open(os.path.join(OUT, q["file"]), "w").write("\n".join(L))

