#!/usr/bin/env python3
"""Generate docs/discovery/domain-diagrams.md: per-domain mermaid ERDs and the cross-domain FK list, from schema.json + domains.json."""
import json, os
root = os.path.join(os.path.dirname(__file__), "..", "..")
S = json.load(open(os.path.join(root, "docs/discovery/schema.json")))["databases"][0]
D = json.load(open(os.path.join(root, "docs/discovery/domains.json")))
owner = {t: n for n, d in D["domains"].items() for t in d["tables"]}
for t in D["excluded"]["tables"]: owner[t] = "(excluded)"
tables = {t["schema"] + "." + t["table"]: t for t in S["tables"]}
missing = sorted(set(tables) - set(owner)); assert not missing, missing
def ent(n): return n.replace(".", "_")
L = ["# Domain diagrams (generated)\n", "Generated by `scripts/discovery/domains.py` from `schema.json` + `domains.json`. "
     "Entities from other domains appear with only their key, marking a cross-domain reference.\n"]
cross = []
for name, d in D["domains"].items():
    L.append("## %s → `%s`\n" % (name, d["table"])); L.append("_%s_\n" % d["rationale"])
    L.append("```mermaid\nerDiagram")
    ext = set()
    for tn in d["tables"]:
        t = tables[tn]
        pk = set(t["primary_key"]); fkc = {c["col"] for f in t["foreign_keys"] for c in f["columns"]}
        L.append("  %s {" % ent(tn))
        for c in t["columns"]:
            if c["name"] in pk or c["name"] in fkc:
                L.append("    %s %s %s" % (c["type"], c["name"], "PK" if c["name"] in pk else "FK"))
        L.append("  }")
        for f in t["foreign_keys"]:
            ref = f["ref_schema"] + "." + f["ref_table"]
            if owner[ref] != name:
                ext.add(ref); cross.append((tn, name, ref, owner[ref], ",".join(c["col"] for c in f["columns"])))
            L.append('  %s ||--o{ %s : "%s"' % (ent(ref), ent(tn), ",".join(c["col"] for c in f["columns"])))
    for r in sorted(ext):
        L.append("  %s {\n    ref %s \"%s domain\"\n  }" % (ent(r), "key", owner[r]))
    L.append("```\n")
L.append("## Cross-domain foreign keys (%d)\n" % len(cross))
L.append("| From (domain) | Column(s) | To (domain) |"); L.append("|---|---|---|")
for a, an, b, bn, c in cross: L.append("| %s (%s) | %s | %s (%s) |" % (a, an, c, b, bn))
open(os.path.join(root, "docs/discovery/domain-diagrams.md"), "w").write("\n".join(L) + "\n")
print(len(cross), "cross-domain FKs")
